'use strict';
// Generates media/icons.js (full Lucide set, ISC) from an unpacked lucide-static package.
// Usage: node scripts/build-icons.js <path-to-lucide-static-package>
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('Informe o caminho do pacote lucide-static descompactado.'); process.exit(1); }
const nodes = JSON.parse(fs.readFileSync(path.join(src, 'icon-nodes.json'), 'utf8'));
const tags = JSON.parse(fs.readFileSync(path.join(src, 'tags.json'), 'utf8'));
const version = JSON.parse(fs.readFileSync(path.join(src, 'package.json'), 'utf8')).version;
const esc = v => String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const icons = {}, keywords = {};
for (const [name, parts] of Object.entries(nodes)) {
  icons[name] = parts.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${esc(v)}"`).join(' ')}/>`).join('');
  const t = (tags[name] || []).slice(0, 6).join(' ');
  if (t) keywords[name] = t;
}
// Names used by earlier versions of the extension keep working.
const aliases = { warning: 'triangle-alert', beaker: 'flask-conical', sparkle: 'sparkles', extensions: 'puzzle', music: 'headphones' };
const out = `// Lucide ${version} - ISC. See lucide-LICENSE.txt. Generated by scripts/build-icons.js; do not edit.\n` +
  `window.toolIcons = ${JSON.stringify(icons)};\nwindow.toolIconTags = ${JSON.stringify(keywords)};\nwindow.toolIconAliases = ${JSON.stringify(aliases)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'media', 'icons.js'), out);
console.log(`${Object.keys(icons).length} ícones, ${(out.length / 1024).toFixed(0)} KB`);
